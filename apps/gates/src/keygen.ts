import { writeFile } from "node:fs/promises";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { ENV_FILE, BURNERS, REPO_ROOT, assertNoKeyOnArgv } from "./config.ts";
import { join } from "node:path";

export interface Burner {
  role: string;
  envName: string;
  privateKey: `0x${string}`;
  evm: `0x${string}`;
  accountId32: string;
}

/**
 * Candidate A: the Substrate account an unmapped Ethereum-derived key is assumed to use.
 * It is the 20 EVM bytes followed by twelve 0xEE bytes. The SS58 prefix is not assumed here.
 */
export function candidateAAccountId32(evmAddress: string): string {
  const hex = evmAddress.toLowerCase().replace(/^0x/, "");
  if (!/^[0-9a-f]{40}$/.test(hex)) throw new Error("expected a 20-byte EVM address");
  return `0x${hex}${"ee".repeat(12)}`;
}

export function generateBurners(): Burner[] {
  return BURNERS.map((spec) => {
    const privateKey = generatePrivateKey();
    const account = privateKeyToAccount(privateKey);
    return {
      role: spec.role,
      envName: spec.envName,
      privateKey,
      evm: account.address.toLowerCase() as `0x${string}`,
      accountId32: candidateAAccountId32(account.address),
    };
  });
}

/** Write the key file with mode 600 and refuse to replace an existing file. */
export async function writeBurnerEnv(path: string, burners: readonly Burner[]): Promise<void> {
  const lines = [
    "# Generated by `npm run keygen`. Never commit this file.",
    "# Burner keys for test funds only. The SS58 faucet address is printed by `g07`.",
    "",
  ];
  for (const burner of burners) lines.push(`${burner.envName}=${burner.privateKey}`);
  lines.push("", "PORTALDOT_EVM_RPC_URL=", "PORTALDOT_WS_URL=", "PORTALDOT_EXPLORER_URL=", "");
  try {
    await writeFile(path, lines.join("\n"), { mode: 0o600, flag: "wx" });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "EEXIST") {
      throw new Error(`refusing to overwrite existing ${path}`);
    }
    throw error;
  }
}

export function printAddresses(burners: readonly Burner[]): void {
  for (const burner of burners) {
    console.log(`${burner.role.padEnd(11)} evm=${burner.evm} accountId32=${burner.accountId32}`);
  }
}

async function main(): Promise<void> {
  assertNoKeyOnArgv();
  const burners = generateBurners();
  await writeBurnerEnv(ENV_FILE, burners);
  console.log(`wrote six burner keys to ${join(REPO_ROOT, ".env")} (mode 600, gitignored)`);
  printAddresses(burners);
  console.log("Add PORTALDOT_EVM_RPC_URL and PORTALDOT_WS_URL to the same file before running g07.");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await main();
}
